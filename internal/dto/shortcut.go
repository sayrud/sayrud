// FieldShortcutManifest describes a field shortcut for the field editor to render the configuration form.
type FieldShortcutManifest struct {
	// ID is the UID of a custom shortcut.
	ID string `json:"id"`
	// Kind is how the shortcut is executed, by a custom script.
	Kind string `json:"kind" enums:"script"`
	// Name is shown in the field editor.
	Name i18n.LocalText `json:"name"`
	// Icon is an optional Lucide icon name or base64 data:image URL.
	Icon string `json:"icon,omitempty"`
	// Color is an optional hex color, empty for the theme color.
	Color string `json:"color,omitempty"`
	// Description tells what the shortcut does.
	Description i18n.LocalText `json:"description"`
	// ResultTypes are the types of the fields the shortcut can be attached to.
	ResultTypes []string `json:"resultTypes"`
	// Sections are the form fields to configure in the field editor.
	Sections []db.ShortcutSection `json:"sections"`
	// Permissions are what the members need to know of the shortcut permissions, the hosts are only shown to the admins.
	Permissions FieldShortcutPermissions `json:"permissions"`
	// Available is false if the shortcut is disabled or its AI configuration is unavailable.
	Available bool `json:"available"`
} // @name FieldShortcutManifest

// FieldShortcutPermissions are the permissions of a shortcut shown to the members.
type FieldShortcutPermissions struct {
	// AI reports whether the script uses the globally configured AI model.
	AI bool `json:"ai"`
} // @name FieldShortcutPermissions

// ShortcutJob is a cell being generated by the shortcut of its field, or failed to.
type ShortcutJob struct {
	// FieldUID is the field of the cell.
	FieldUID string `json:"fieldUID"`
	// RecordUID is the record of the cell.
	RecordUID string `json:"recordUID"`
	// Status is done when the job is removed, which is only sent over WebSocket.
	Status string `json:"status" enums:"pending,running,failed,done"`
	// Error is the reason of the failure, or of the last attempt of a pending retry.
	Error string `json:"error,omitempty"`
} // @name ShortcutJob

// ShortcutJobsMessage is the data of the SHORTCUT_JOBS WebSocket message.
type ShortcutJobsMessage struct {
	// TableUID is the table of the jobs.
	TableUID string `json:"tableUID"`
	// Reload tells the client to fetch all the jobs of the table instead, e.g. too many cells are changed.
	Reload bool `json:"reload,omitempty"`
	// Jobs are the changed jobs, empty if Reload is true.
	Jobs []*ShortcutJob `json:"jobs"`
} // @name ShortcutJobsMessage

// RunFieldShortcutResp is the result of queuing the cells to generate.
type RunFieldShortcutResp struct {
	// Count is the number of the cells queued.
	Count int `json:"count"`
} // @name RunFieldShortcutResp

// ShortcutPreview is the result of the shortcut on a record, which is not written back.
type ShortcutPreview struct {
	// RecordUID is the record previewed.
	RecordUID string `json:"recordUID"`
	// Value is the cell value of the field, null if empty or failed.
	Value interface{} `json:"value,omitempty" swaggertype:"object"`
	// Error is the reason of the failure, empty if succeeded.
	Error string `json:"error,omitempty"`
} // @name ShortcutPreview

// AdminFieldShortcut is a custom field shortcut for the admins, the credential values are not returned.
type AdminFieldShortcut struct {
	// UID is the identifier the fields refer to the shortcut by.
	UID string `json:"uid"`
	// ID is the source package identifier, empty if not declared; UID identifies this installation.
	ID string `json:"id"`
	// Homepage is the project website or support page declared by the source.
	Homepage string `json:"homepage"`
	// Name is shown in the field editor.
	Name i18n.LocalText `json:"name"`
	// Icon is an optional Lucide icon name or base64 data:image URL.
	Icon string `json:"icon,omitempty"`
	// Color is an optional hex color, empty for the theme color.
	Color string `json:"color,omitempty"`
	// Version is the version declared by the shortcut manifest.
	Version string `json:"version"`
	// Description tells the members what the shortcut does.
	Description i18n.LocalText `json:"description"`
	// ResultType is the type of the fields the shortcut can be attached to.
	ResultType string `json:"resultType"`
	// Timeout is the time limit of an execution in seconds.
	Timeout int `json:"timeout"`
	// Permissions are the hosts the script can fetch and whether it can use the globally configured AI model.
	Permissions db.ShortcutPermissions `json:"permissions"`
	// Credentials are the credentials the script can use when fetching.
	Credentials []*AdminCredential `json:"credentials"`
	// Sections are the form fields configured in the field editor and passed to execute as the params.
	Sections []db.ShortcutSection `json:"sections"`
	// Code defines `async function execute(params, context)` returning the cell value, with context.ai.complete using the global model when permissions.ai is true.
	Code string `json:"code"`
	// Language is the language of the saved source.
	Language string `json:"language" enums:"javascript,typescript"`
	// Enabled reports whether the members can attach and execute the shortcut.
	Enabled bool `json:"enabled"`
	// UsedBy is the number of the fields using the shortcut.
	UsedBy int64 `json:"usedBy"`
	// Hub is the Sayrud Hub release the shortcut is installed from, omitted if installed from elsewhere.
	Hub *HubOrigin `json:"hub,omitempty"`
	// Signature is the verified Sayrud Hub signature of Code to send back when installing, only returned when inspecting a release.
	Signature json.RawMessage `json:"signature,omitempty" swaggertype:"object"`
	// CreatedAt is the time the shortcut was created.
	CreatedAt time.Time `json:"createdAt"`
	// UpdatedAt is the time the shortcut was last updated.
	UpdatedAt time.Time `json:"updatedAt"`
} // @name AdminFieldShortcut

// ListAdminFieldShortcutsResp is a page of shortcuts matching the admin search.
type ListAdminFieldShortcutsResp struct {
	Shortcuts []*AdminFieldShortcut `json:"shortcuts"`
	Total     int64                 `json:"total"`
} // @name ListAdminFieldShortcutsResp

// AdminCredential is a credential of a custom shortcut, HasValue reports whether its value is saved.
type AdminCredential struct {
	Key      string         `json:"key"`
	Label    i18n.LocalText `json:"label"`
	Type     string         `json:"type" enums:"bearer,header,query"`
	Name     string         `json:"name,omitempty"`
	HasValue bool           `json:"hasValue"`
} // @name AdminCredential

// ToAdminFieldShortcut converts the custom shortcut, keys are the credentials with saved values.
func ToAdminFieldShortcut(s *db.CustomFieldShortcut, valueKeys map[string]bool, usedBy int64) *AdminFieldShortcut {
	credentials := make([]*AdminCredential, 0, len(s.Credentials.Data()))
	for _, c := range s.Credentials.Data() {
		label := c.Label
		if strings.TrimSpace(label.In("en")) == "" {
			label = i18n.LocalText{"": c.Key}
		}
		credentials = append(credentials, &AdminCredential{Key: c.Key, Label: label, Type: string(c.Type), Name: c.Name, HasValue: valueKeys[c.Key]})
	}

	language := s.Language
	if language == "" {
		language = "javascript"
	}
	version := s.Version
	if version == "" {
		version = "1.0.0"
	}

	return &AdminFieldShortcut{
		UID:         s.UID,
		ID:          s.ManifestID,
		Homepage:    s.Homepage,
		Name:        s.Name,
		Icon:        s.Icon,
		Color:       s.Color,
		Version:     version,
		Description: s.Description,
		ResultType:  string(s.ResultType),
		Timeout:     s.TimeoutSeconds,
		Permissions: ShortcutPermissions(s),
		Credentials: credentials,
		Sections:    ShortcutSections(s),
		Code:        s.Code,
		Language:    language,
		Enabled:     s.Enabled,
		UsedBy:      usedBy,
		Hub:         ToHubOrigin(s.HubSignature),
		CreatedAt:   s.CreatedAt,
		UpdatedAt:   s.UpdatedAt,
	}
}

// ShortcutPermissions returns the permissions of the shortcut.
func ShortcutPermissions(s *db.CustomFieldShortcut) db.ShortcutPermissions {
	fetch := s.Domains.Data()
	if fetch == nil {
		fetch = []string{}
	}
	return db.ShortcutPermissions{Fetch: fetch, AI: s.AIEnabled}
}

// ShortcutSections returns the form sections of the shortcut, empty instead of nil.
func ShortcutSections(s *db.CustomFieldShortcut) []db.ShortcutSection {
	if sections := s.Sections.Data(); sections != nil {
		return sections
	}
	return []db.ShortcutSection{}
}

